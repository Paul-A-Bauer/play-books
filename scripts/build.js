#!/usr/bin/env node
// Builds dist/play-books.html (single self-contained page).
const fs = require('fs'), path = require('path');
const { CORE, UI } = require('./sources');
const R = p => path.join(__dirname, '..', p);
const TEMPLATE_FILES = { level: 'level.pug', main: 'main.js', pkg: 'package.json', readme: 'README.md' };

function generateTemplates() {
  const t = {};
  for (const k in TEMPLATE_FILES) t[k] = fs.readFileSync(R('src/export/templates/' + TEMPLATE_FILES[k]), 'utf8');
  fs.mkdirSync(R('src/generated'), { recursive: true });
  fs.writeFileSync(R('src/generated/templates.js'),
    '// GENERATED by scripts/build.js from src/export/templates/. Do not edit.\nconst TEMPLATES = ' + JSON.stringify(t, null, 2) + ';\n');
}

function build() {
  generateTemplates();
  const script = [...CORE, ...UI]
    .map(f => '// ---- ' + f + '\n' + fs.readFileSync(R(f), 'utf8'))
    .join('\n').replace(/<\/script/gi, '<\\/script');
  const html = fs.readFileSync(R('src/index.template.html'), 'utf8')
    .replace('/*STYLES*/', () => fs.readFileSync(R('src/styles.css'), 'utf8'))
    .replace('/*SCRIPT*/', () => script);
  fs.mkdirSync(R('dist'), { recursive: true });
  fs.writeFileSync(R('dist/play-books.html'), html);
  console.log('Built dist/play-books.html (' + Math.round(html.length / 1024) + ' KB)');
}

module.exports = { generateTemplates, build };
if (require.main === module) build();
